use anyhow::Result;
use target_lexicon::Triple;
use tarvos_ir::{FormatPart, Module, Stmt, UnaryOp, Value};

#[allow(dead_code)]
#[allow(dead_code)]
const TAG_NONE: i64 = 0;
#[allow(dead_code)]
const TAG_INT: i64 = 1;
#[allow(dead_code)]
const TAG_FLOAT: i64 = 2;
#[allow(dead_code)]
const TAG_BOOL: i64 = 3;
#[allow(dead_code)]
const TAG_STRING: i64 = 4;
#[allow(dead_code)]
const TAG_LIST: i64 = 5;
#[allow(dead_code)]
const TAG_DICT: i64 = 6;
#[allow(dead_code)]
const TAG_SET: i64 = 7;

pub fn compile_to_clif(module: &Module) -> Result<String> {
    let mut clif_parts: Vec<String> = Vec::new();
    clif_parts.push("; Module generated by tarvos-codegen-cranelift".to_string());
    clif_parts.push(format!("; target: {}", Triple::host().to_string()));
    clif_parts.push(String::new());
    for stmt in &module.statements {
        let clif = stmt_to_clif(stmt, 0)?;
        clif_parts.push(clif);
        clif_parts.push(String::new());
    }
    Ok(clif_parts.join("\n"))
}

fn stmt_to_clif(stmt: &Stmt, indent: usize) -> Result<String> {
    let pad = "  ".repeat(indent);
    match stmt {
        Stmt::Let { name, ty, value } => Ok(format!(
            "{}let {} = {};  ;; type: {:?}",
            pad,
            name,
            value_to_clif(value)?,
            ty
        )),
        Stmt::Print(values) => {
            let vals: Vec<String> = values
                .iter()
                .map(|v| value_to_clif(v))
                .collect::<Result<Vec<_>>>()?;
            Ok(format!("{}print {};", pad, vals.join(", ")))
        }
        Stmt::If { test, body, orelse } => {
            let test_clif = value_to_clif(test)?;
            let mut lines = vec![format!("{}if {} {{", pad, test_clif)];
            for s in body {
                lines.push(stmt_to_clif(s, indent + 1)?);
            }
            lines.push(format!("{}}}", pad));
            if !orelse.is_empty() {
                lines.push(format!("{}else {{", pad));
                for s in orelse {
                    lines.push(stmt_to_clif(s, indent + 1)?);
                }
                lines.push(format!("{}}}", pad));
            }
            Ok(lines.join("\n"))
        }
        Stmt::While { test, body } => {
            let test_clif = value_to_clif(test)?;
            let mut lines = vec![format!("{}loop {{  ;; while {}", pad, test_clif)];
            for s in body {
                lines.push(stmt_to_clif(s, indent + 1)?);
            }
            lines.push(format!("{}}}", pad));
            Ok(lines.join("\n"))
        }
        Stmt::For { target, body, .. } => {
            let mut lines = vec![format!("{}for {} in iter {{", pad, target)];
            for s in body {
                lines.push(stmt_to_clif(s, indent + 1)?);
            }
            lines.push(format!("{}}}", pad));
            Ok(lines.join("\n"))
        }
        Stmt::Function {
            name,
            params,
            return_type,
            body,
        } => {
            let param_str: Vec<String> = params
                .iter()
                .map(|(n, t)| format!("{}: {:?}", n, t))
                .collect();
            let mut lines = vec![format!(
                "{}function {} ({}) -> {:?} {{",
                pad,
                name,
                param_str.join(", "),
                return_type
            )];
            for s in body {
                lines.push(stmt_to_clif(s, indent + 1)?);
            }
            lines.push(format!("{}}}", pad));
            Ok(lines.join("\n"))
        }
        Stmt::Return(val) => match val {
            Some(v) => Ok(format!("{}return {};", pad, value_to_clif(v)?)),
            None => Ok(format!("{}return;", pad)),
        },
        Stmt::Pass => Ok(format!("{}nop;", pad)),
        Stmt::Break => Ok(format!("{}break;", pad)),
        Stmt::Continue => Ok(format!("{}continue;", pad)),
        Stmt::Expr(val) => Ok(format!("{}eval {};", pad, value_to_clif(val)?)),
        Stmt::Assign { name, value } => {
            Ok(format!("{}set {} = {};", pad, name, value_to_clif(value)?))
        }
        Stmt::StructDef { name, fields } => {
            let field_str: Vec<String> = fields
                .iter()
                .map(|(n, t)| format!("{}: {:?}", n, t))
                .collect();
            Ok(format!(
                "{}struct {} {{{}}};",
                pad,
                name,
                field_str.join(", ")
            ))
        }
        Stmt::ListAppend { target, value } => Ok(format!(
            "{}list_append {} {};",
            pad,
            target,
            value_to_clif(value)?
        )),
        Stmt::IndexAssign {
            target,
            indices,
            value,
        } => {
            let idx_str: Vec<String> = indices
                .iter()
                .map(|v| value_to_clif(v))
                .collect::<Result<Vec<_>>>()?;
            Ok(format!(
                "{}set_index {} [{}] = {};",
                pad,
                target,
                idx_str.join(", "),
                value_to_clif(value)?
            ))
        }
        Stmt::Destructure { targets, value } => Ok(format!(
            "{}destructure {} = {};",
            pad,
            targets.join(", "),
            value_to_clif(value)?
        )),
        Stmt::FieldAssign {
            object,
            field,
            value,
        } => Ok(format!(
            "{}set_field {} .{} = {};",
            pad,
            value_to_clif(object)?,
            field,
            value_to_clif(value)?
        )),
        Stmt::Raise(val) => match val {
            Some(v) => Ok(format!("{}raise {};", pad, value_to_clif(v)?)),
            None => Ok(format!("{}raise;", pad)),
        },
        Stmt::Try { .. } => Ok(format!("{};; try statement (lowered by Rust codegen)", pad)),
        Stmt::With { .. } => Ok(format!(
            "{};; with statement (lowered by Rust codegen)",
            pad
        )),
    }
}

fn value_to_clif(value: &Value) -> Result<String> {
    match value {
        Value::Int(n) => Ok(n.to_string()),
        Value::Int128(n) => Ok(format!("i128({})", n)),
        Value::Float(f) => Ok(f.to_string()),
        Value::String(s) => Ok(format!("\"{}\"", s)),
        Value::Bool(b) => Ok(b.to_string()),
        Value::None => Ok("none".to_string()),
        Value::Name(n) => Ok(format!("${}", n)),
        Value::Binary {
            left, op, right, ..
        } => Ok(format!(
            "({} {} {})",
            value_to_clif(left)?,
            op.symbol(),
            value_to_clif(right)?
        )),
        Value::Unary { op, operand, .. } => {
            let sym = match op {
                UnaryOp::Neg => "-",
                UnaryOp::Not => "not",
                UnaryOp::Invert => "~",
            };
            Ok(format!("({} {})", sym, value_to_clif(operand)?))
        }
        Value::Call { function, args, .. } => {
            let arg_str: Vec<String> = args
                .iter()
                .map(|v| value_to_clif(v))
                .collect::<Result<Vec<_>>>()?;
            Ok(format!("{}({})", function, arg_str.join(", ")))
        }
        Value::Index {
            container, index, ..
        } => Ok(format!(
            "{}[{}]",
            value_to_clif(container)?,
            value_to_clif(index)?
        )),
        Value::Slice { container, .. } => Ok(format!("slice({})", value_to_clif(container)?)),
        Value::MethodCall {
            object,
            method,
            args,
            ..
        } => {
            let arg_str: Vec<String> = args
                .iter()
                .map(|v| value_to_clif(v))
                .collect::<Result<Vec<_>>>()?;
            Ok(format!(
                "{}.{}({})",
                value_to_clif(object)?,
                method,
                arg_str.join(", ")
            ))
        }
        Value::FormatString { parts } => {
            let part_strs: Vec<String> = parts
                .iter()
                .map(|p| match p {
                    FormatPart::Literal(s) => Ok(format!("\"{}\"", s)),
                    FormatPart::Value { value, .. } => value_to_clif(value),
                })
                .collect::<Result<Vec<_>>>()?;
            Ok(format!("fstring({})", part_strs.join(", ")))
        }
        _ => Ok(format!("{{/* unsupported value */}}")),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use tarvos_types::Type;

    #[test]
    fn test_compile_to_clif_empty() {
        let module = Module { statements: vec![] };
        let clif = compile_to_clif(&module).unwrap();
        assert!(clif.contains("tarvos-codegen-cranelift"));
    }

    #[test]
    fn test_compile_to_clif_let() {
        let module = Module {
            statements: vec![Stmt::Let {
                name: "x".to_string(),
                ty: Type::Int,
                value: Value::Int(42),
            }],
        };
        let clif = compile_to_clif(&module).unwrap();
        assert!(clif.contains("let x = 42"));
    }

    #[test]
    fn test_compile_to_clif_print() {
        let module = Module {
            statements: vec![Stmt::Print(vec![Value::Int(1), Value::Int(2)])],
        };
        let clif = compile_to_clif(&module).unwrap();
        assert!(clif.contains("print"));
    }
}
